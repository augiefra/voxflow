// MARK: - Aides Accessibilité

public enum AXHelper {
    /// Navigateurs Chromium (hors Electron) : ils ignorent `AXManualAccessibility`
    /// et n'exposent leurs champs qu'avec `AXEnhancedUserInterface`.
    public static let chromiumBrowsers: Set<String> = [
        "com.google.Chrome", "com.google.Chrome.canary", "com.brave.Browser", "com.microsoft.edgemac",
        "company.thebrowser.Browser", "com.vivaldi.Vivaldi", "com.operasoftware.Opera", "org.chromium.Chromium",
    ]

    private static var primedPIDs = Set<pid_t>()

    public static func isTrusted(prompt: Bool) -> Bool {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: prompt] as CFDictionary
        return AXIsProcessTrustedWithOptions(options)
    }

    public static func attribute(_ element: AXUIElement, _ name: String) -> CFTypeRef? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success else { return nil }
        return value
    }

    public static func string(_ element: AXUIElement, _ name: String) -> String? {
        guard let value = attribute(element, name) else { return nil }
        if let text = value as? String { return text }
        if let attributed = value as? NSAttributedString { return attributed.string }
        return nil
    }

    public static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        guard let value = attribute(system, kAXFocusedUIElementAttribute),
              CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let element = value as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.25)
        return element
    }

    public static func pid(of element: AXUIElement) -> pid_t? {
        var pid: pid_t = 0
        return AXUIElementGetPid(element, &pid) == .success ? pid : nil
    }

    /// Plage sélectionnée (unités UTF-16, comme `NSString`).
    public static func selectedRange(_ element: AXUIElement) -> NSRange? {
        guard let value = attribute(element, kAXSelectedTextRangeAttribute),
              CFGetTypeID(value) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(value as! AXValue, .cfRange, &range) else { return nil }
        return NSRange(location: range.location, length: range.length)
    }

    public static func isSecureField(_ element: AXUIElement) -> Bool {
        let role = string(element, kAXRoleAttribute) ?? ""
        let subrole = string(element, kAXSubroleAttribute) ?? ""
        return role == "AXSecureTextField" || subrole == kAXSecureTextFieldSubrole
    }

    /// Astuce Chromium/Electron : force VS Code, Cursor, Slack, Chrome… à construire
    /// leur arbre d'accessibilité. À appeler dès le début de la dictée pour laisser
    /// à l'app le temps de l'exposer avant le collage.
    public static func primeAccessibility(for app: NSRunningApplication) {
        let pid = app.processIdentifier
        guard pid > 0, !primedPIDs.contains(pid) else { return }
        let appElement = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(appElement, 0.25)
        let manual = AXUIElementSetAttributeValue(appElement, "AXManualAccessibility" as CFString, kCFBooleanTrue)
        if manual != .success, let bundleID = app.bundleIdentifier, chromiumBrowsers.contains(bundleID) {
            _ = AXUIElementSetAttributeValue(appElement, "AXEnhancedUserInterface" as CFString, kCFBooleanTrue)
        }
        primedPIDs.insert(pid)
    }
}

// MARK: - Collage sans perte du presse-papier

public final class TextInjector {
    public init() {}

    /// Sauvegarde le presse-papier, colle `text` par Cmd+V, puis restaure le
    /// presse-papier après `restoreAfter` (sauf si quelqu'un l'a modifié entre-temps).
    public func paste(_ text: String, restoreAfter: TimeInterval = 0.150, completion: @escaping () -> Void) {
        let pasteboard = NSPasteboard.general
        let saved = Self.snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Conventions nspasteboard.org : les gestionnaires d'historique ignorent ce contenu.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        Self.postCommandV()

        DispatchQueue.main.asyncAfter(deadline: .now() + restoreAfter) {
            if pasteboard.changeCount == ourChangeCount {
                pasteboard.clearContents()
                if !saved.isEmpty { pasteboard.writeObjects(saved) }
            }
            completion()
        }
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .privateState)
        let keyCode = CGKeyCode(keyCode(for: "v") ?? UInt16(kVK_ANSI_V))
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: GlobalEventTap.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// Touche qui produit `character` dans la disposition clavier active (AZERTY, Dvorak…).
    static func keyCode(for character: Character) -> UInt16? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let rawLayout = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let layoutData = Unmanaged<CFData>.fromOpaque(rawLayout).takeUnretainedValue() as Data
        return layoutData.withUnsafeBytes { buffer -> UInt16? in
            guard let layout = buffer.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in UInt16(0)..<128 {
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), 0, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeyState,
                                            chars.count, &length, &chars)
                if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1) == String(character) {
                    return code
                }
            }
            return nil
        }
    }
}

// MARK: - Contexte au moment du collage (T_paste)

public struct PasteContext {
    public let insertedText: String
    public let bundleID: String
    public let pid: pid_t
    public let element: AXUIElement?
    /// Valeur complète du champ juste après le collage (nil : AX inexploitable).
    public let valueAfterPaste: String?
    /// Position du texte inséré dans `valueAfterPaste` (UTF-16).
    public let insertion: NSRange?
    public let isSecure: Bool

    public var usesAccessibility: Bool { element != nil && valueAfterPaste != nil && insertion != nil }

    /// Lit l'élément focalisé, sa valeur et la position du texte inséré.
    public static func capture(insertedText: String, app: NSRunningApplication?) -> PasteContext {
        let bundleID = app?.bundleIdentifier ?? ""
        let pid = app?.processIdentifier ?? 0
        guard let element = AXHelper.focusedElement() else {
            return PasteContext(insertedText: insertedText, bundleID: bundleID, pid: pid, element: nil,
                                valueAfterPaste: nil, insertion: nil, isSecure: false)
        }
        let elementPID = AXHelper.pid(of: element) ?? pid
        let secure = AXHelper.isSecureField(element)
        let value = secure ? nil : AXHelper.string(element, kAXValueAttribute)
        var insertion: NSRange?
        if let value, (value as NSString).length <= 500_000 {
            insertion = locate(insertedText, in: value, caret: AXHelper.selectedRange(element))
        }
        return PasteContext(insertedText: insertedText, bundleID: bundleID, pid: elementPID, element: element,
                            valueAfterPaste: insertion == nil ? nil : value, insertion: insertion, isSecure: secure)
    }

    /// Le curseur se trouve normalement juste après le texte collé ; à défaut on
    /// cherche la dernière occurrence avant lui.
    static func locate(_ inserted: String, in value: String, caret: NSRange?) -> NSRange? {
        let full = value as NSString
        let length = (inserted as NSString).length
        guard length > 0, full.length >= length else { return nil }
        if let caret {
            let start = caret.location - length
            if start >= 0, start + length <= full.length, full.substring(with: NSRange(location: start, length: length)) == inserted {
                return NSRange(location: start, length: length)
            }
            let searchEnd = min(full.length, caret.location + caret.length + length)
            let found = full.range(of: inserted, options: .backwards, range: NSRange(location: 0, length: searchEnd))
            if found.location != NSNotFound { return found }
        }
        let found = full.range(of: inserted, options: .backwards)
        return found.location == NSNotFound ? nil : found
    }
}

// MARK: - Zone corrigée après la surveillance

public enum CorrectionSegments {
    /// Isole, dans la valeur finale du champ, la zone qui correspond au texte collé :
    /// tout ce qui précède et suit l'insertion et n'a pas bougé est retiré.
    public static func extract(initialFull: String, insertion: NSRange, finalFull: String) -> (initial: String, final: String) {
        let a = Array(initialFull.utf16)
        let b = Array(finalFull.utf16)
        let insertionEnd = min(a.count, insertion.location + insertion.length)
        var prefix = 0
        while prefix < min(a.count, b.count, insertion.location), a[prefix] == b[prefix] { prefix += 1 }
        let maxSuffix = min(a.count - insertionEnd, b.count - prefix)
        var suffix = 0
        while suffix < maxSuffix, a[a.count - 1 - suffix] == b[b.count - 1 - suffix] { suffix += 1 }

        let initialSegment = String(utf16CodeUnits: Array(a[prefix..<(a.count - suffix)]), count: a.count - suffix - prefix)
        let finalLength = max(0, b.count - suffix - prefix)
        let finalSegment = finalLength == 0 ? "" : String(utf16CodeUnits: Array(b[prefix..<(prefix + finalLength)]), count: finalLength)
        return (expandToWords(initialSegment, in: initialFull, from: prefix),
                expandToWords(finalSegment, in: finalFull, from: prefix))
    }

    /// Recolle les morceaux de mots coupés au bord de la zone (ex. préfixe commun « Fa »).
    private static func expandToWords(_ segment: String, in full: String, from offset: Int) -> String {
        let ns = full as NSString
        var start = offset
        var end = offset + (segment as NSString).length
        let letters = CharacterSet.alphanumerics
        func isLetter(_ index: Int) -> Bool {
            guard index >= 0, index < ns.length, let scalar = Unicode.Scalar(ns.character(at: index)) else { return false }
            return letters.contains(scalar)
        }
        while start > 0, isLetter(start - 1) { start -= 1 }
        while end < ns.length, isLetter(end) { end += 1 }
        return ns.substring(with: NSRange(location: start, length: end - start))
    }
}

// MARK: - Fallback : reconstruction par les frappes (Terminal…)

/// Reconstitue en mémoire les modifications appliquées à `Texte_Initial` à partir des
/// frappes. Renvoie `false` dès que le suivi devient incertain (curseur sorti de la
/// zone collée, annulation, flèches haut/bas…) : la surveillance s'arrête alors avec
/// le dernier état fiable.
public struct KeystrokeShadowBuffer {
    public private(set) var characters: [Character]
    public private(set) var cursor: Int
    private var anchor: Int?

    private static let functionKeys: Set<Int> = [
        kVK_F1, kVK_F2, kVK_F3, kVK_F4, kVK_F5, kVK_F6, kVK_F7, kVK_F8, kVK_F9, kVK_F10,
        kVK_F11, kVK_F12, kVK_F13, kVK_F14, kVK_F15, kVK_F16, kVK_F17, kVK_F18, kVK_F19, kVK_F20,
    ]

    public init(text: String) {
        characters = Array(text)
        cursor = characters.count
    }

    public var text: String { String(characters) }

    private var selection: Range<Int>? {
        guard let anchor, anchor != cursor else { return nil }
        return min(anchor, cursor)..<max(anchor, cursor)
    }

    public mutating func apply(keyCode: Int64, flags: CGEventFlags, characters typed: String, pasteboard: () -> String?) -> Bool {
        let command = flags.contains(.maskCommand)
        let option = flags.contains(.maskAlternate)
        let control = flags.contains(.maskControl)
        let shift = flags.contains(.maskShift)

        let code = Int(keyCode)
        if Self.functionKeys.contains(code) || code == kVK_Escape { return true }
        switch code {
        case kVK_Delete:
            if deleteSelection() { return true }
            if command { return deleteBackward(to: 0) }
            if option { return deleteBackward(to: wordStart(before: cursor)) }
            return deleteBackward(to: cursor - 1)
        case kVK_ForwardDelete:
            if deleteSelection() { return true }
            return deleteForward(to: cursor + 1)
        case kVK_LeftArrow, kVK_RightArrow:
            let left = code == kVK_LeftArrow
            var target: Int
            if command { target = left ? 0 : characters.count }
            else if option { target = left ? wordStart(before: cursor) : wordEnd(after: cursor) }
            else if !shift, let selection { target = left ? selection.lowerBound : selection.upperBound }
            else { target = cursor + (left ? -1 : 1) }
            if target < 0 || target > characters.count { return false }
            move(to: target, extending: shift)
            return true
        case kVK_Home:
            move(to: 0, extending: shift); return true
        case kVK_End:
            move(to: characters.count, extending: shift); return true
        case kVK_UpArrow, kVK_DownArrow, kVK_PageUp, kVK_PageDown, kVK_Tab:
            return false
        default:
            break
        }

        if command {
            switch typed.lowercased() {
            case "v":
                guard let pasted = pasteboard() else { return false }
                _ = deleteSelection()
                insert(pasted); return true
            case "x":
                _ = deleteSelection(); return true
            case "c":
                return true
            default:
                return false // Cmd+Z, Cmd+A… : état impossible à suivre
            }
        }
        if control {
            switch typed {
            case "\u{01}": move(to: 0, extending: false); return true                 // Ctrl+A
            case "\u{05}": move(to: characters.count, extending: false); return true  // Ctrl+E
            case "\u{02}":                                                            // Ctrl+B
                guard cursor > 0 else { return false }
                move(to: cursor - 1, extending: false); return true
            case "\u{06}":                                                            // Ctrl+F
                guard cursor < characters.count else { return false }
                move(to: cursor + 1, extending: false); return true
            case "\u{08}": return deleteBackward(to: cursor - 1)                      // Ctrl+H
            case "\u{04}": return deleteForward(to: cursor + 1)                       // Ctrl+D
            case "\u{17}": return deleteBackward(to: wordStart(before: cursor))       // Ctrl+W
            case "\u{15}": return deleteBackward(to: 0)                               // Ctrl+U
            case "\u{0B}": return deleteForward(to: characters.count)                 // Ctrl+K
            default: return false
            }
        }
        let printable = typed.unicodeScalars.allSatisfy { !CharacterSet.controlCharacters.contains($0) }
        guard !typed.isEmpty, printable else { return true }
        // Les caractères composés avec Option (« œ », « … ») arrivent déjà traduits dans `typed`.
        _ = deleteSelection()
        insert(typed)
        return true
    }

    private mutating func move(to position: Int, extending: Bool) {
        if extending { if anchor == nil { anchor = cursor } } else { anchor = nil }
        cursor = position
    }

    private mutating func insert(_ string: String) {
        characters.insert(contentsOf: Array(string), at: cursor)
        cursor += string.count
        anchor = nil
    }

    private mutating func deleteSelection() -> Bool {
        guard let selection else { anchor = nil; return false }
        characters.removeSubrange(selection)
        cursor = selection.lowerBound
        anchor = nil
        return true
    }

    private mutating func deleteBackward(to target: Int) -> Bool {
        anchor = nil
        guard target >= 0, target <= cursor else { return false }
        characters.removeSubrange(target..<cursor)
        cursor = target
        return true
    }

    private mutating func deleteForward(to target: Int) -> Bool {
        anchor = nil
        guard target <= characters.count, target >= cursor else { return false }
        characters.removeSubrange(cursor..<target)
        return true
    }

    private func wordStart(before index: Int) -> Int {
        var i = index
        while i > 0, !characters[i - 1].isLetter && !characters[i - 1].isNumber { i -= 1 }
        while i > 0, characters[i - 1].isLetter || characters[i - 1].isNumber { i -= 1 }
        return i
    }

    private func wordEnd(after index: Int) -> Int {
        var i = index
        while i < characters.count, !characters[i].isLetter && !characters[i].isNumber { i += 1 }
        while i < characters.count, characters[i].isLetter || characters[i].isNumber { i += 1 }
        return i
    }
}

// MARK: - Surveillance post-collage (CorrectionWatcher)

public protocol CorrectionWatcherDelegate: AnyObject {
    /// Fin de la fenêtre : `initial` = texte collé (zone), `final` = même zone après corrections.
    func correctionWatcher(_ watcher: CorrectionWatcher, didFinishWith initial: String, final: String, bundleID: String)
}

/// Pendant 25 s après un collage (ou jusqu'au changement de focus, Entrée, Cmd+Entrée) :
/// méthode primaire = valeur AX observée (notifications + relecture périodique) ;
/// fallback = `KeystrokeShadowBuffer` quand l'app n'expose pas `kAXValueAttribute`.
public final class CorrectionWatcher {
    public enum EndReason: String {
        case timeout, focusChanged, submitted, superseded, lostTrack, mouseClick
    }

    private enum Mode {
        case accessibility(element: AXUIElement, initialFull: String, insertion: NSRange, latest: String)
        case shadow(KeystrokeShadowBuffer, initial: String)
    }

    public weak var delegate: CorrectionWatcherDelegate?
    public let duration: TimeInterval
    public var pollInterval: TimeInterval = 0.3
    public private(set) var isActive = false

    private let tap: GlobalEventTap
    private var mode: Mode?
    private var bundleID = ""
    private var pid: pid_t = 0
    private var tapHandler: UUID?
    private var observer: AXObserver?
    private var timers: [Timer] = []
    private var workspaceObserver: NSObjectProtocol?
    private var focusMismatches = 0

    public init(tap: GlobalEventTap, duration: TimeInterval = 25) {
        self.tap = tap
        self.duration = duration
    }

    public func begin(context: PasteContext) {
        if isActive { end(.superseded) }
        guard !context.isSecure, !context.insertedText.isEmpty else { return }
        bundleID = context.bundleID
        pid = context.pid
        focusMismatches = 0

        if context.usesAccessibility, let element = context.element,
           let value = context.valueAfterPaste, let insertion = context.insertion {
            mode = .accessibility(element: element, initialFull: value, insertion: insertion, latest: value)
            installAXObserver(on: element)
            schedule(every: pollInterval) { [weak self] in self?.poll() }
        } else {
            mode = .shadow(KeystrokeShadowBuffer(text: context.insertedText), initial: context.insertedText)
        }
        isActive = true

        tapHandler = tap.addHandler { [weak self] event in self?.handle(event) }
        schedule(after: duration) { [weak self] in self?.end(.timeout) }
        workspaceObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            guard let self,
                  let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  app.processIdentifier != self.pid else { return }
            self.end(.focusChanged)
        }
    }

    public func end(_ reason: EndReason) {
        guard isActive, let mode else { return }
        isActive = false
        timers.forEach { $0.invalidate() }
        timers.removeAll()
        if let tapHandler { tap.removeHandler(tapHandler) }
        tapHandler = nil
        if let workspaceObserver { NSWorkspace.shared.notificationCenter.removeObserver(workspaceObserver) }
        workspaceObserver = nil
        if let observer {
            CFRunLoopRemoveSource(CFRunLoopGetMain(), AXObserverGetRunLoopSource(observer), .defaultMode)
        }
        observer = nil
        self.mode = nil

        let initial: String
        let final: String
        switch mode {
        case let .accessibility(element, initialFull, insertion, latest):
            // Relecture finale, sauf si le champ a pu être vidé (envoi) ou a perdu le focus.
            var value = latest
            if reason == .timeout, let fresh = AXHelper.string(element, kAXValueAttribute) { value = fresh }
            (initial, final) = CorrectionSegments.extract(initialFull: initialFull, insertion: insertion, finalFull: value)
        case let .shadow(buffer, text):
            (initial, final) = (text, buffer.text)
        }
        guard initial != final else { return }
        delegate?.correctionWatcher(self, didFinishWith: initial, final: final, bundleID: bundleID)
    }

    // MARK: Méthode primaire : AXUIElement

    private func installAXObserver(on element: AXUIElement) {
        var created: AXObserver?
        let callback: AXObserverCallback = { _, _, notification, refcon in
            guard let refcon else { return }
            let watcher = Unmanaged<CorrectionWatcher>.fromOpaque(refcon).takeUnretainedValue()
            if (notification as String) == kAXFocusedUIElementChangedNotification
                || (notification as String) == kAXUIElementDestroyedNotification {
                watcher.end(.focusChanged)
            } else {
                watcher.poll()
            }
        }
        guard AXObserverCreate(pid, callback, &created) == .success, let created else { return }
        let refcon = Unmanaged.passUnretained(self).toOpaque()
        AXObserverAddNotification(created, element, kAXValueChangedNotification as CFString, refcon)
        AXObserverAddNotification(created, element, kAXUIElementDestroyedNotification as CFString, refcon)
        AXObserverAddNotification(created, AXUIElementCreateApplication(pid), kAXFocusedUIElementChangedNotification as CFString, refcon)
        CFRunLoopAddSource(CFRunLoopGetMain(), AXObserverGetRunLoopSource(created), .defaultMode)
        observer = created
    }

    /// Relit la valeur (et vérifie le focus) : couvre les apps qui n'envoient pas
    /// de notifications de changement.
    private func poll() {
        guard isActive, case let .accessibility(element, initialFull, insertion, _) = mode else { return }
        // Chromium renvoie parfois un autre objet pour le même champ : on n'arrête que
        // si le focus a quitté l'app, ou s'il reste ailleurs deux relectures de suite.
        if let focused = AXHelper.focusedElement(), !CFEqual(focused, element) {
            focusMismatches += 1
            if AXHelper.pid(of: focused) != pid || focusMismatches >= 2 {
                end(.focusChanged)
                return
            }
        } else {
            focusMismatches = 0
        }
        guard let value = AXHelper.string(element, kAXValueAttribute) else {
            end(.focusChanged)
            return
        }
        mode = .accessibility(element: element, initialFull: initialFull, insertion: insertion, latest: value)
    }

    // MARK: Événements clavier / souris

    private func handle(_ event: GlobalEventTap.Event) {
        guard isActive, let mode else { return }
        switch event {
        case let .keyDown(keyCode, flags, characters, _):
            if Int(keyCode) == kVK_Return || Int(keyCode) == kVK_ANSI_KeypadEnter {
                // Le tap voit la frappe avant l'app : on capture le texte avant l'envoi.
                if case .accessibility = mode { poll() }
                end(.submitted)
                return
            }
            guard case .shadow(var buffer, let initial) = mode else { return }
            let tracked = buffer.apply(keyCode: keyCode, flags: flags, characters: characters) {
                NSPasteboard.general.string(forType: .string)
            }
            if tracked {
                self.mode = .shadow(buffer, initial: initial)
            } else {
                end(.lostTrack)
            }
        case .mouseDown:
            // En AX, un clic dans le champ pour corriger est normal ; en fallback, on
            // ne sait plus où est le curseur : on garde le dernier état fiable.
            if case .shadow = mode { end(.mouseClick) }
        case .flagsChanged, .scroll:
            break
        }
    }

    private func schedule(after delay: TimeInterval, _ block: @escaping () -> Void) {
        let timer = Timer(timeInterval: delay, repeats: false) { _ in block() }
        RunLoop.main.add(timer, forMode: .common)
        timers.append(timer)
    }

    private func schedule(every interval: TimeInterval, _ block: @escaping () -> Void) {
        let timer = Timer(timeInterval: interval, repeats: true) { _ in block() }
        RunLoop.main.add(timer, forMode: .common)
        timers.append(timer)
    }
}
